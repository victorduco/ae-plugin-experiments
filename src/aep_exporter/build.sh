#!/bin/bash
# build.sh — concatenate module files into a single deployable ExtendScript bundle.
# Output: dist/aep_exporter_bundle.jsx
#
# Module files are raw declarations (no IIFE) — only main.jsx opens the IIFE.
# Concatenation order follows dependency chain: core → properties → footage →
# shapes → transform → effects → layers → comps → main.

set -euo pipefail

EXPORTER_DIR="$(cd "$(dirname "$0")" && pwd)"
DIST="$EXPORTER_DIR/dist"
BUNDLE="$DIST/aep_exporter_bundle.jsx"

mkdir -p "$DIST"

MODULES=(
    "$EXPORTER_DIR/modules/core.jsx"
    "$EXPORTER_DIR/modules/properties.jsx"
    "$EXPORTER_DIR/modules/footage.jsx"
    "$EXPORTER_DIR/modules/shapes.jsx"
    "$EXPORTER_DIR/modules/transform.jsx"
    "$EXPORTER_DIR/modules/effects.jsx"
    "$EXPORTER_DIR/modules/masks.jsx"
    "$EXPORTER_DIR/modules/layers.jsx"
    "$EXPORTER_DIR/modules/comps.jsx"
    "$EXPORTER_DIR/main.jsx"
)

# Verify all module files exist before writing anything
for MOD in "${MODULES[@]}"; do
    if [[ ! -f "$MOD" ]]; then
        echo "ERROR: missing module file: $MOD" >&2
        exit 1
    fi
done

# Write bundle header
cat > "$BUNDLE" <<'HEADER'
// AUTO-GENERATED by build.sh — do not edit directly.
// Edit the source modules in src/aep_exporter/modules/ instead.
HEADER
echo "// Generated: $(date)" >> "$BUNDLE"
echo "" >> "$BUNDLE"

# Concatenate modules in order
for MOD in "${MODULES[@]}"; do
    echo "" >> "$BUNDLE"
    echo "// ─── $(basename "$MOD") ──────────────────────────────────────────" >> "$BUNDLE"
    cat "$MOD" >> "$BUNDLE"
done

LINES=$(wc -l < "$BUNDLE")
echo "Bundle: $BUNDLE ($LINES lines)"
